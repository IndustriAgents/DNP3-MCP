from __future__ import annotations

from typing import Any, Protocol


class DNP3MasterPort(Protocol):
    config: Any

    def shutdown(self, reason: Any) -> Any: ...

    def read_deadline_s(self) -> Any: ...

    def control_deadline_s(self) -> Any: ...

    async def read_binary_inputs(self, outstation: Any, start: Any, count: Any, *, request_scope: Any = ...) -> Any: ...

    async def read_analog_inputs(self, outstation: Any, start: Any, count: Any, *, request_scope: Any = ...) -> Any: ...

    async def poll_class(self, outstation: Any, event_class: Any, *, request_scope: Any = ...) -> Any: ...

    async def write_binary_output(
        self, outstation: Any, index: Any, value: Any, *, request_scope: Any = ...
    ) -> Any: ...

    def connection_status(self) -> Any: ...

    async def close(self) -> Any: ...
